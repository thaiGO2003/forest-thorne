function hashString(text: unknown): number {
  const input = String(text ?? "");
  let hash = 0;
  for (let i = 0; i < input.length; i += 1) {
    hash = (hash * 31 + input.charCodeAt(i)) >>> 0;
  }
  return hash;
}

function pickBySeed(list: unknown, seed: number): unknown {
  if (!Array.isArray(list) || list.length === 0) return null;
  return list[Math.abs(seed) % list.length];
}

function shiftColor(color: unknown, delta: number): number {
  const source = Number(color) >>> 0;
  const clamp = (value: number): number => Math.max(0, Math.min(255, value));
  const r = clamp(((source >> 16) & 0xff) + delta);
  const g = clamp(((source >> 8) & 0xff) + delta);
  const b = clamp((source & 0xff) + delta);
  return (r << 16) | (g << 8) | b;
}

function slugify(text: unknown): string {
  return String(text ?? "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "") || "skin";
}

