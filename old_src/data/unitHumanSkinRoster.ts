function createTheme(meta: Record<string, unknown>, variantIndex: number): Record<string, unknown> {
  const seed = hashString(`${meta.id}:${variantIndex}:${meta.classType}:${meta.tribe}`);
  const classType = typeof meta.classType === "string" ? meta.classType : "FIGHTER";
  const tribe = typeof meta.tribe === "string" ? meta.tribe : "DEFAULT";
  const classPool = CLASS_THEME_LIBRARY[classType] ?? CLASS_THEME_LIBRARY.FIGHTER;
  const classTheme = (pickBySeed(classPool, seed + variantIndex * 11) as Record<string, unknown> | null) ?? classPool[0];
  const altClassTheme = (pickBySeed(classPool, seed + variantIndex * 17 + 3) as Record<string, unknown> | null) ?? classPool[1] ?? classPool[0];
  const tribeStyle = TRIBE_STYLE_LIBRARY[tribe] ?? TRIBE_STYLE_LIBRARY.DEFAULT;
  const titlePair = variantIndex === 0
    ? `${classTheme.titleVi} ${tribeStyle.titleVi}`
    : `${tribeStyle.titleVi} ${altClassTheme.titleVi}`;
  const titlePairEn = variantIndex === 0
    ? `${classTheme.titleEn} ${tribeStyle.titleEn}`
    : `${tribeStyle.titleEn} ${altClassTheme.titleEn}`;
  const classIcons = Array.isArray(classTheme.icons) ? classTheme.icons : [];
  const iconByStar: Record<number, unknown> = {
    1: classIcons[0] ?? tribeStyle.accentEmoji ?? meta.icon ?? "🧑",
    2: classIcons[1] ?? tribeStyle.accentEmoji ?? meta.icon ?? "✨",
    3: classIcons[2] ?? tribeStyle.accentEmoji ?? meta.icon ?? "💫"
  };
  const titleSeed = `${meta.id}_${titlePairEn}_${variantIndex + 1}`;
  return {
    baseNameVi: meta.nameVi,
    baseNameEn: meta.nameEn,
    skinKey: `${meta.id}_${slugify(titleSeed)}`,
    nameVi: titlePair,
    nameEn: titlePairEn,
    iconByStar,
    ribbonColor: shiftColor(tribeStyle.ribbonColor, variantIndex * 6),
    haloColor: shiftColor(tribeStyle.haloColor, variantIndex * 10),
    hairColor: shiftColor(classTheme.hairColor ?? tribeStyle.hairColor, variantIndex * 4),
    outfitColor: shiftColor(classTheme.outfitColor ?? tribeStyle.outfitColor, variantIndex * 4),
    dressColor: shiftColor(classTheme.dressColor ?? tribeStyle.dressColor, variantIndex * 4),
    skirtColor: shiftColor(classTheme.skirtColor ?? tribeStyle.skirtColor, variantIndex * 4),
    weaponColor: shiftColor(classTheme.weaponColor ?? tribeStyle.weaponColor, variantIndex * 6),
    skinTone: tribeStyle.skinTone,
    headAccessory: classTheme.headAccessory ?? tribeStyle.headAccessory,
    speciesAccent: classTheme.speciesAccent ?? tribeStyle.speciesAccent,
    sideAccent: classTheme.sideAccent ?? tribeStyle.sideAccent,
    auraShape: classTheme.auraShape ?? tribeStyle.auraShape,
    weaponType: classTheme.weaponType ?? "spear",
    accentEmoji: classTheme.accentEmoji ?? tribeStyle.accentEmoji ?? meta.icon ?? "🌟",
    mature: true,
    variantIndex
  };
}

export const UNIT_HUMAN_SKIN_ROSTER = Object.freeze(Object.fromEntries(
  Object.entries(UNIT_CORE_META).map(([unitId, meta]) => [
    unitId,
    Object.freeze([
      Object.freeze(createTheme({ ...meta, id: unitId }, 0)),
      Object.freeze(createTheme({ ...meta, id: unitId }, 1))
    ])
  ])
));

export function getHumanSkinThemesForUnit(unitId: string): readonly Record<string, unknown>[] {
  return UNIT_HUMAN_SKIN_ROSTER[unitId] ?? [];
}
